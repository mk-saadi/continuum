const { app, BrowserWindow } = require('electron');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
app.disableHardwareAcceleration();
app.on("window-all-closed", event => event.preventDefault());
app.whenReady().then(async () => {
 const directory = await fs.mkdtemp('/tmp/workspace-editor-ui-');
 const win = new BrowserWindow({ show: true, width: 900, height: 650, webPreferences: { sandbox: true } });
 win.webContents.on("console-message", (_event, _level, message) => console.log(message));
 try {
  await require('esbuild').build({ stdin: { contents: `
   import React, {useRef} from 'react'; import {createRoot} from 'react-dom/client';
   import Editor from './src/components/WorkspaceFileEditor.jsx';
   window.api = {writeWorkspaceFile: async (...args) => { window.savedArgs = args; }};
   function Demo() { const drafts = useRef({}); const [wrap, setWrap] = React.useState(false); window.setWrap = setWrap; return <Editor onAddToChat={excerpt => { window.fileExcerpt = excerpt; }} wrap={wrap} projectId="project" path="test.js" language="javascript" content="const hello = hello;" drafts={drafts}>{text => <pre>{text}</pre>}</Editor>; }
   createRoot(document.getElementById('root')).render(<Demo/>);
  `, resolveDir: process.cwd(), loader: 'jsx' }, bundle: true, outfile: directory + '/app.js', loader: { '.css': 'empty' } });
  const styles = (await fs.readdir('dist/assets')).filter(file => file.endsWith('.css'));
  await fs.writeFile(directory + '/style.css', (await Promise.all(styles.map(file => fs.readFile('dist/assets/' + file, 'utf8')))).join('\n') + await fs.readFile('src/components/workspaceFileEditor.css', 'utf8'));
  await fs.writeFile(directory + '/index.html', '<link rel="stylesheet" href="style.css"><div id="root" style="height:100vh;display:flex"></div><script src="app.js"></script>');
  await win.loadFile(directory + '/index.html');
  await new Promise(resolve => setTimeout(resolve, 200));
  assert.equal(await win.webContents.executeJavaScript(`(async () => {
   const wait = () => new Promise(r => setTimeout(r, 50));
   const check = (v, msg) => { if (!v) throw Error(msg); };
   const button = text => [...document.querySelectorAll('button')].find(b => b.textContent === text);
   check(!button('Save'), 'save button removed');
   const source = document.querySelector('.file-code-paint');
   source.dispatchEvent(new PointerEvent('pointerdown', {bubbles:true, buttons:1}));
   const selectedRange = document.createRange(); selectedRange.selectNodeContents(source);
   window.getSelection().removeAllRanges(); window.getSelection().addRange(selectedRange); await wait();
   check(!document.querySelector('[aria-label="Add file selection to chat"]'), 'preview popover hidden during drag');
   document.dispatchEvent(new PointerEvent('pointerup', {bubbles:true})); await wait();
   document.querySelector('[aria-label="Add file selection to chat"]').click(); await wait();
   check(window.fileExcerpt === 'test.js:1' + String.fromCharCode(10,10) + 'const hello = hello;', 'preview adds source without gutter numbers');
   check(!window.savedArgs, 'adding selection does not save file');
   window.getSelection().removeAllRanges(); await wait();
   document.querySelector('[aria-label="Find in file"]').click(); await wait();
   check(!document.querySelector('textarea'), 'preview find keeps preview mode');
   const previewInput = document.querySelector('input');
   Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(previewInput,'hello'); previewInput.dispatchEvent(new Event('input',{bubbles:true})); await wait();
   check(document.querySelector('[role="search"]').textContent.includes('1/2'), 'preview find count');
   check([...CSS.highlights.values()].some(h => h.size === 2), 'preview highlights both matches');
   button('Edit').click(); await wait();
   check(document.querySelector('[role="search"]'), 'find remains open across mode switch');
   check(document.querySelector('.file-code-paint span[style*="--code-keyword"]'), 'editing has syntax highlighting');
   check(document.querySelector('.react-syntax-highlighter-line-number'), 'editing has line numbers');
   const editor = document.querySelector('textarea');
   window.paintMutations = 0;
   const paintObserver = new MutationObserver(records => { window.paintMutations += records.length; });
   paintObserver.observe(document.querySelector('.file-code-paint'), {subtree:true,childList:true,characterData:true});
   const setter = Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set;
   setter.call(editor, 'const hello = hello; // edited'); editor.dispatchEvent(new Event('input', {bubbles:true})); await wait();
   check(editor.value === 'const hello = hello; // edited', 'edit');
   editor.dispatchEvent(new PointerEvent('pointerdown', {bubbles:true, buttons:1}));
   editor.focus(); editor.setSelectionRange(6, 11); await wait();
   check(!document.querySelector('[aria-label="Add file selection to chat"]'), 'edit popover hidden during drag');
   document.dispatchEvent(new PointerEvent('pointerup', {bubbles:true})); await wait();
   document.querySelector('[aria-label="Add file selection to chat"]').click(); await wait();
   check(window.fileExcerpt === 'test.js:1 (unsaved edits)' + String.fromCharCode(10,10) + 'hello', 'edit adds current selected draft with provenance');
   document.querySelector('[aria-label="Undo file edit"]').click(); await wait(); check(editor.value === 'const hello = hello;', 'undo');
   document.querySelector('[aria-label="Redo file edit"]').click(); await wait(); check(editor.value.endsWith('edited'), 'redo');
   editor.dispatchEvent(new KeyboardEvent('keydown', {key:'s',ctrlKey:true,bubbles:true})); await wait(); check(window.savedArgs[2] === editor.value && window.savedArgs[3] === 'const hello = hello;', 'save expected content');
   editor.dispatchEvent(new KeyboardEvent('keydown', {key:'f',ctrlKey:true,bubbles:true})); await wait();
   const input = document.querySelector('input');
   Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'hello'); input.dispatchEvent(new Event('input',{bubbles:true})); await wait();
   check(document.querySelector('[role="search"]').textContent.includes('1/2'), 'find count');
   await wait(); window.paintMutations = 0;
   document.querySelector('[aria-label="Next match (Enter)"]').click(); await wait(); check(editor.selectionStart === 14, 'next match');
   document.querySelector('[aria-label="Previous match (Shift+Enter)"]').click(); await wait(); check(editor.selectionStart === 6, 'previous match');
   check(window.paintMutations === 0, 'find navigation does not rerender syntax layer');
   paintObserver.disconnect();
   const paint = document.querySelector('.file-code-paint');
   const range = document.createRange(); range.selectNodeContents(paint.querySelector('span[style*="--code-keyword"]'));
   const rect = range.getBoundingClientRect();
   const box = editor.getBoundingClientRect();
   check(Math.abs(rect.left - (box.left + 64 - editor.scrollLeft)) < 2, 'highlight aligns with input text');
   const multiline = Array.from({length: 80}, (_, i) => 'const line' + i + ' = "' + 'long text '.repeat(20) + '";').join(String.fromCharCode(10));
   setter.call(editor, multiline); editor.dispatchEvent(new Event('input', {bubbles:true})); await wait();
   check(document.querySelectorAll('.react-syntax-highlighter-line-number').length === 80, 'line count follows edits');
   const numbers = document.querySelectorAll('.react-syntax-highlighter-line-number');
   check(Math.abs(numbers[1].getBoundingClientRect().top - numbers[0].getBoundingClientRect().top - 18) < 1, 'line height matches input');
   editor.scrollTop = 240; editor.scrollLeft = 100; editor.dispatchEvent(new Event('scroll')); await wait();
   check(paint.style.transform.includes('-240px'), 'vertical scroll stays aligned');
   check(paint.style.transform.includes('-100px'), 'horizontal scroll stays aligned');
   button('Preview').click(); await wait(); check(!paint.style.transform, 'preview clears editor scroll transform');
   const surface = document.querySelector('.file-code-surface');
   check(surface.scrollTop === 240 && surface.scrollLeft === 100, 'edit to preview preserves both scroll axes');
   surface.scrollTop = 400; surface.scrollLeft = 160;
   button('Edit').click(); await wait();
   const restored = document.querySelector('textarea');
   check(restored.scrollTop === 400 && restored.scrollLeft === 160, 'preview to edit preserves both scroll axes');
   check(surface.scrollTop === 0 && surface.scrollLeft === 0, 'input scrolling is not doubled by surface');
   const selected = getComputedStyle(restored, '::selection');
   const probe = document.createElement('span'); probe.style.backgroundColor = 'var(--accent)'; document.body.append(probe);
   check(selected.backgroundColor === getComputedStyle(probe).backgroundColor, 'selection uses theme accent'); probe.remove();
   check(selected.webkitTextFillColor === selected.color && selected.color !== 'rgba(0, 0, 0, 0)', 'selected text stays opaque');
   window.setWrap(true); await wait();
   const wrappedNumbers = document.querySelectorAll('.react-syntax-highlighter-line-number');
   check(wrappedNumbers[1].getBoundingClientRect().top - wrappedNumbers[0].getBoundingClientRect().top > 18, 'wrapped lines retain line numbers');
   for (let i=0; i<15; i++) {
    document.querySelector('[aria-label="Close find (Escape)"]').click(); await wait();
    check(CSS.highlights.size === 0, 'closed find releases ranges');
    check(![...document.head.querySelectorAll('style')].some(style => style.textContent.includes('::highlight(file-find-')), 'closed find releases style');
    document.querySelector('[aria-label="Find in file"]').click(); await wait();
   }
   const selectedEditor = document.querySelector('textarea');
   setter.call(selectedEditor, 'const selected = 42;'); selectedEditor.dispatchEvent(new Event('input', {bubbles:true})); await wait();
   selectedEditor.focus({preventScroll:true}); selectedEditor.setSelectionRange(0, 20); await wait();
   selectedEditor.scrollTop = 0; selectedEditor.scrollLeft = 0; selectedEditor.dispatchEvent(new Event('scroll')); await wait();
   return true;
  })()`), true);
  await fs.writeFile('/tmp/workspace-file-editor.png', (await win.webContents.capturePage()).toPNG());
  console.log('File editing, undo, redo, save and find passed.');
 } finally { win.destroy(); await fs.rm(directory, {recursive:true,force:true}); }
}).then(() => app.quit()).catch(error => { console.error(error); app.exit(1); });
